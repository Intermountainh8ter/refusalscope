"""Suite B: indirect prompt injection (generator, agent loop, deterministic grader, mock oracle).

Each case is a benign user task in one of nine fake tool environments, plus an attacker goal
(a call to an attacker-chosen function with an attacker-chosen value) delivered through an
injection vector. Every case is run twice: ``control`` (clean data) and ``attack`` (payload
inserted). Graders look only at the stored transcript.
"""

